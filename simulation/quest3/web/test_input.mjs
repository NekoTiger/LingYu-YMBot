function quatMat(q){
  const x=q[0],y=q[1],z=q[2],w=q[3];
  return [[1-2*(y*y+z*z),2*(x*y-w*z),2*(x*z+w*y)],[2*(x*y+w*z),1-2*(x*x+z*z),2*(y*z-w*x)],[2*(x*z-w*y),2*(y*z+w*x),1-2*(x*x+y*y)]];
}
function apply(m,v){return m.map(row=>row[0]*v[0]+row[1]*v[1]+row[2]*v[2]);}
